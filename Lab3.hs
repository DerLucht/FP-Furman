-- Замикання (closure) — це функція, яка використовує значення з навколишньої області видимості, тобто з того місця, де вона була визначена.
-- лок визначення


import Data.IORef 
-- модуль, який дозволяє зберігати та змінювати значення в пам'яті, щоб лічильник пам'ятав кількість попередніх викликів.

newCounter :: IO (IO Int) 
-- ф яка створює новий лічильник. Тип IO (IO Int) означає, що створення лічильника виконує операцію введення-виведення, а результатом є дія, яка при кожному виконанні повертає ціле число.

newCounter = do
    ref <- newIORef 0
	-- комірка пам зі зн 0
    let counter = do
	-- локальну дію counter усередині newCounter. це локальне визначення має доступ до ref, створеного зовнішньою функцією.
            n <- readIORef ref
		-- поточне зн лічильника
            let next = n + 1
            writeIORef ref next
            return next
    return counter

main = do
    counter <- newCounter
    a <- counter
    print a
    b <- counter
    print b
    c <- counter
    print c

-- Спочатку створюємо лічильник, а потім тричі його викликаємо. Кожен виклик збільшує збережене значення на одиницю.